const BS_EPOCH = { year: 2000, month: 1, day: 1 };
const AD_EPOCH = new Date(1943, 3, 14); // April 14, 1943

function daysInBSYear(year: number): number {
  return (BS_MONTHS_DATA[year] ?? []).reduce((s, d) => s + d, 0);
}

/** Convert AD date to BS */
export function adToBS(adDate: Date): { year: number; month: number; day: number } {
  const diff = Math.floor((adDate.getTime() - AD_EPOCH.getTime()) / 86400000);
  let remaining = diff;
  let { year, month, day } = BS_EPOCH;

  while (remaining > 0) {
    const daysInMonth = BS_MONTHS_DATA[year]?.[month - 1] ?? 30;
    if (remaining < daysInMonth - day + 1) { day += remaining; remaining = 0; }
    else {
      remaining -= daysInMonth - day + 1;
      day = 1;
      if (month === 12) { month = 1; year++; } else month++;
    }
  }
  return { year, month, day };
}

/** Format AD date as BS string */
export function formatBS(adDate: Date | string | null | undefined, format: "full" | "short" = "full"): string {
  if (!adDate) return "—";
  const d = typeof adDate === "string" ? new Date(adDate) : adDate;
  if (isNaN(d.getTime())) return "—";
  try {
    const { year, month, day } = adToBS(d);
    const months = ["बैशाख","जेठ","आषाढ","श्रावण","भाद्र","आश्विन","कार्तिक","मंसिर","पौष","माघ","फाल्गुन","चैत्र"];
    if (format === "short") return `${year}-${String(month).padStart(2,"0")}-${String(day).padStart(2,"0")}`;
    return `${day} ${months[month - 1]} ${year}`;
  } catch {
    return d.toLocaleDateString();
  }
}

/** Format as "YYYY-MM-DD BS" short label */
export function bsShort(adDate: Date | string | null | undefined): string {
  return formatBS(adDate, "short");
}
